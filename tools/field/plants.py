"""Растительность: сколько земли под зеленью, клетка за клеткой.

Отдельный растр, а не оттенок в чужой шкале (владелец 2026-09-11: «давай
сделаем отдельную симуляцию роста растительности, чтобы равнины имели не
зелёный цвет, а только растительность имела зелёный цвет»).

**Зачем отдельно.** Зелёный цвет до сих пор жил в трёх местах сразу и ни в
одном не означал растений: в гипсометрической шкале высот (низина зелёная,
потому что на Земле низины зелёные), в легенде форм (равнина зелёная, потому
что она равнина) и в таблице зональных биомов (лес зелёный по имени). Оттого
Пироксис выходил травянистым, а Аврора — луговой: цвет говорил о **форме**, а
читался как **жизнь**. Разведя их, мы получаем и правду, и свободу: земля
красится породой, зелень — покровом, и на планете без покрова зелени просто
нет, без единой оговорки про планету.

**Что решает покров.** Четыре вещи, все — из растров, которые поле уже имеет.

1. **Тепло.** Растёт в полосе `terrain.plant_temp`: у холодного края покров
   сходит на нет (тундра, мох, голый камень), у тёплого — тоже (жара сушит
   быстрее, чем дождь поливает). Полоса, а не порог: жизнь кончается не
   ступенькой.
2. **Вода.** Дождь по шкале `site.rain_range` плюс близость пресной воды:
   пойма зеленее степи вокруг неё при том же небе, и это видно на любой
   настоящей карте.
3. **Опора.** Голый камень держит меньше почвы, чем рыхлый нанос
   (`hardness`), а крутизна сносит её вовсе.
4. **Лёд и расплав** снимают покров начисто: под шапкой и на потоке лавы не
   растёт ничего, каким бы ни был климат.

Числа полосы — в реестре, форма кривых — здесь: где растёт, решает вольт, а
чем именно гаснет — устройство модели.
"""

from __future__ import annotations

import numpy as np

from field.grid import Grid

#: Ширина плеча тепловой полосы — доля её половины, на которой покров сходит
#: с единицы до нуля у края. Плато с плечами, а не пик: в середине полосы
#: жизни одинаково хорошо, и убывать она начинает у самой границы. Считалось
#: сперва степенью от середины — и умеренный лес выходил покровом в пять
#: процентов, потому что три множителя меньше единицы дают в произведении
#: ничтожество.
TEMP_SHOULDER = 0.35
#: Доля покрова, которую даёт одна близость пресной воды при нулевом дожде:
#: пойма зелена и в степи, но лугом посреди пустыни не станет.
WET_SHARE = 0.45
#: Уклон, на котором почвы не остаётся вовсе, м/м. Выше — голый камень.
BARE_SLOPE = 0.6
#: Сколько покрова теряет самая твёрдая порода против самой рыхлой. Мягкая
#: не теряет ничего: на наносе растёт всё, что климат позволяет.
HARD_LOSS = 0.35
#: Края шкалы твёрдости поля (`plates.HARD_*`): по ним потеря нормируется.
HARD_SOFT, HARD_FIRM = 0.25, 1.0


def _plateau(value: np.ndarray, low: float, high: float, shoulder: float) -> np.ndarray:
    """Единица в середине полосы, ноль за краями, плечо между ними."""
    half = max((high - low) / 2.0, 1e-9)
    off = np.abs(value - (high + low) / 2.0) / half
    edge = max(shoulder, 1e-9)
    return np.clip((1.0 - off) / edge, 0.0, 1.0)


def cover(
    grid: Grid,
    *,
    temperature_c: np.ndarray,
    rain01: np.ndarray,
    river_m: np.ndarray,
    height_m: np.ndarray,
    hardness: np.ndarray,
    land: np.ndarray,
    barren: np.ndarray,
    warm_c: float,
    cold_c: float,
    rain_full: float,
    wet_km: float,
) -> np.ndarray:
    """Доля клетки под растительностью, [0, 1].

    `barren` — клетки, где не растёт ничего независимо от климата: лёд,
    лава, вода. `warm_c` и `cold_c` — края полосы роста (`terrain.plant_temp`),
    `rain_full` — доля шкалы осадков, при которой воды уже вдоволь
    (`terrain.plant_rain`), `wet_km` — на каком удалении от пресной воды её
    близость перестаёт помогать (`biome.facet_axes.wet_km`, та же длина, что
    у оси влаги).

    Три множителя, и каждый **насыщается**: полный покров наступает задолго
    до края шкалы. Иначе они перемножаются в ничто — умеренный лес выходил
    покровом в пять процентов при том, что каждый сомножитель по отдельности
    выглядел разумно.
    """
    warmth = _plateau(temperature_c, cold_c, warm_c, TEMP_SHOULDER)

    #: Вода: дождь плюс близость реки или озера, и вдоволь её задолго до
    #: верха шкалы — на диаграмме Уиттекера лес начинается с середины.
    near = np.clip(1.0 - river_m / max(wet_km * 1000.0, 1e-9), 0.0, 1.0)
    water = np.clip((rain01 + WET_SHARE * near) / max(rain_full, 1e-9), 0.0, 1.0)

    #: Опора: крутизна сносит почву, твёрдая порода её не держит. Мягкая не
    #: отнимает ничего — на наносе растёт всё, что позволил климат.
    slope = np.clip(1.0 - grid.slope(height_m) / BARE_SLOPE, 0.0, 1.0)
    firm = np.clip((hardness - HARD_SOFT) / max(HARD_FIRM - HARD_SOFT, 1e-9), 0.0, 1.0)
    soil = slope * (1.0 - HARD_LOSS * firm)

    out = warmth * water * soil
    return np.where(land & ~barren, out, 0.0)
